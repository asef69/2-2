n.p("With ε-moves (Sipser, textbook): start = E({q0}) and δ′(R, a) = E(∪ δ(r, a)). If |Q| = n the DFA has at most 2^n "
    "states; build only the reachable ones (**lazy evaluation**).")
n.h2("2. Worked Example: Contains aba (sl. 97–108)")
