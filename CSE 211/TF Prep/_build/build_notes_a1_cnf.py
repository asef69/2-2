# ---------------------------------------------------------- L2
n.lesson("Lesson 2 — Simplifying Grammars", "Lecture 2, slides 19–30")
n.h2("1. Useless Symbols (sl. 22–23)")
n.p("X is **generating** if X ⇒∗ w for some terminal string w (every terminal is generating). X is **reachable** if "
    "S ⇒∗ αXβ. X is **useful** if it is both, i.e. it appears in some derivation of a terminal string from S; otherwise "
    "useless. Find generating symbols inductively (terminals; then any A with a body of generating symbols), delete the "
    "non-generating ones, THEN find reachable symbols from S and delete the rest.")
n.code(["S → AB | a,  A → b       B is not generating → delete S → AB:  S → a,  A → b",
        "                         A is not reachable  → delete A:        S → a          (sl. 23)"])
n.callout("trap", "Order matters: generating first, then reachable. In the other order a symbol made unreachable only by "
          "deleting a non-generating production would survive (here A).")
n.h2("2. ε-Productions (sl. 24–26)")
n.p("A is **nullable** if A ⇒∗ ε (basis: A → ε; induction: A → C1…Ck with all Ci nullable). For every production with "
    "nullable symbols in its body, add all versions with any subset of those symbols removed (but never add A → ε). If the "
    "language contains ε, keep S → ε (Hopcroft: the grammar is then 'CNF + S → ε').")
n.code(["S → AB,  A → aAA | ε,  B → bBB | ε          nullable: A, B, S",
        "S → AB | A | B,  A → aAA | aA | a,  B → bBB | bB | b,   and add S → ε (S nullable)   (sl. 25–26)"])
n.h2("3. Unit Productions (sl. 27–30)")
n.p("A unit production is A → B (both variables). (A, B) is a **unit pair** if A ⇒∗ B using unit productions only "
    "((A, A) by zero steps). For each unit pair (A, B) add A → α for every non-unit production B → α; then drop all unit "
    "productions.")
fig(n, "A2", 29, "Figure 2.1 — Unit pairs and the productions kept for E/T/F/I (sl. 29)", clip=K, width_cm=11)
n.h2("Exam Approach")
n.numbered(["List nullable variables; rewrite every production (all subsets); note whether ε ∈ L.",
            "List unit pairs (closure); replace unit productions.",
            "Remove non-generating, then unreachable symbols.",
            "Show the grammar after each step — the marks are per step."])
n.practice("Lesson 2", "(a)–(c) Actual — 2008-09 Q2(a)–(c).",
           ["(a) For S → ASB | ε, A → aAS | a, B → SbS | A | bb eliminate ε-productions. (7⅓)",
            "(b) Eliminate unit productions. (8)", "(c) Eliminate useless symbols. (8)"])
n.solution()
n.answer("(a)", "Nullable: S only (A and B always produce a terminal). Remove S from bodies in all ways:")
n.code(["S → ASB | AB",
        "A → aAS | aA | a",
        "B → SbS | Sb | bS | b | A | bb          (ε ∈ L, so the language is L(G′) ∪ {ε}; keep S → ε separately if required)"])
n.answer("(b)", "Unit pairs: (S,S), (A,A), (B,B), (B,A). Replace B → A by A's non-unit bodies:")
n.code(["S → ASB | AB",
        "A → aAS | aA | a",
        "B → SbS | Sb | bS | b | bb | aAS | aA | a"])
n.answer("(c)", "Generating: a, b; A (A → a); B (B → b); S (S → AB). All generating. Reachable from S: A, B (and a, b). "
         "No useless symbols — the grammar of (b) is final. (Both steps were checked: the language is unchanged on all "
         "strings up to length 6.)")

