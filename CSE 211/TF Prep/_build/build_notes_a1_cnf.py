n.lesson("Lesson 3 — Converting to Chomsky Normal Form", "Lecture 2, slides 2–3, 19–21, 31–35")
n.callout("memorize", "CNF: every production is A → BC (two variables) or A → a (one terminal), and there are no useless "
          "symbols (sl. 2). Every non-empty CFL without ε has a CNF grammar; with ε, add S → ε (S not on any right side). "
          "Order (sl. 21): (1) eliminate ε-productions, (2) eliminate unit productions, (3) eliminate useless symbols, "
          "(4a) put terminals of long bodies into new variables (A → a), (4b) break bodies of length ≥ 3 into chains.")
n.h2("1. Steps 4a and 4b — Worked Example (sl. 32–35)")
fig(n, "A2", 34, "Figure 3.1 — Replacing terminals in long bodies by new variables (sl. 34)", clip=K, width_cm=11)
fig(n, "A2", 35, "Figure 3.2 — Breaking bodies of length 3 with C1 → PT, C2 → MF, C3 → ER (sl. 35)", clip=K, width_cm=11)
n.p("A body X1X2…Xk (k ≥ 3) becomes A → X1C1, C1 → X2C2, …, C(k−2) → X(k−1)Xk.")
n.h2("Exam Approach")
n.numbered(["Write the original language in one line if easy — it helps you check the result.",
            "Do steps 1–3 exactly as in Lesson 2, showing the grammar after each.",
            "New variables for terminals (Z → 0, U → 1); new variables for long bodies.",
            "Check: every rule is A → BC or A → a (plus S → ε if ε ∈ L); derive one short string."])
n.callout("trap", "Never leave A → ε or A → B in the final grammar; never replace a lone terminal body A → 0 by a variable; "
          "keep ε only as S → ε for the (new) start symbol.")
n.practice("Lesson 3", "(a) Actual — 2021-22 Q5 / 2017-18 Q7(a). (b) Actual — 2016-17 Q6(b) / 2014-15 Q5(c).",
           ["(a) Convert S → A1A | B, A → 0A | 1A | ε, D → 00 (2017-18; in 2021-22 the last rule is B → 1) into an equivalent "
            "grammar in CNF. Show the steps. (8–15)",
            "(b) What is CNF? Convert A → BAB | B | ε, B → 00 | ε into an equivalent grammar in CNF. (9⅓–10)"])
n.solution()
n.answer("(a)", "L(G) = binary strings containing at least one 1 (S → A1A, A = (0 ∪ 1)∗).")
n.code(["Step 1 (ε): nullable A.   S → A1A | 1A | A1 | 1 | B     A → 0A | 0 | 1A | 1     D → 00   (2021-22: B → 1)",
        "Step 2 (unit): unit pair (S,B).  2017-18: B has no productions → S → B simply disappears.",
        "                                 2021-22: S → B, B → 1 gives S → 1 (already present).",
        "Step 3 (useless): B is not generating (2017-18); D is not reachable (2017-18). Remove both.",
        "        S → A1A | 1A | A1 | 1        A → 0A | 1A | 0 | 1",
        "Step 4a: Z → 0, U → 1.   S → AUA | UA | AU | 1     A → ZA | UA | 0 | 1",
        "Step 4b: S → AUA becomes S → VA, V → AU.",
        "CNF:  S → VA | UA | AU | 1      V → AU      A → ZA | UA | 0 | 1      Z → 0      U → 1"], size=8.5)
n.p("Checked: the CNF grammar generates exactly the strings with at least one 1 (all strings up to length 7).")
n.answer("(b)", "CNF definition: Lesson 3 box. L = {(00)^k | k ≥ 0} — note ε ∈ L.")
n.code(["Step 1 (ε): nullable A, B.  A → BAB | AB | BA | BB | B | A   (drop A → A)     B → 00",
        "            ε ∈ L → new start S0 → A | ε",
        "Step 2 (unit): A → B gives A → 00;  S0 → A gives S0 → (all A bodies)",
        "        S0 → BAB | AB | BA | BB | 00 | ε      A → BAB | AB | BA | BB | 00      B → 00",
        "Step 3 (useless): none.",
        "Step 4a: Z → 0:  …… 00 becomes ZZ",
        "Step 4b: BAB becomes BC with C → AB",
        "CNF:  S0 → BC | AB | BA | BB | ZZ | ε     A → BC | AB | BA | BB | ZZ     C → AB     B → ZZ     Z → 0"], size=8.5)
n.p("Checked: the CNF grammar (with S0 → ε) generates exactly (00)∗ up to length 8.")

# ---------------------------------------------------------- L4
n.lesson("Lesson 4 — The CYK Membership Algorithm", "Lecture 2, slides 4–18")
n.p("CYK (Cocke–Younger–Kasami) decides w ∈ L(G) for a CNF grammar G in O(n³) time by dynamic programming (sl. 4). "
    "X_{ij} = set of variables A with A ⇒∗ a_{i}…a_{j} (sl. 8); w ∈ L iff S ∈ X_{1n} (sl. 9).")
n.formula(["X_{ii} = { A | A → a_{i} }", "A ∈ X_{ij}  ⇔  ∃k, i ≤ k < j, B ∈ X_{ik}, C ∈ X_{k+1,j}, A → BC"])
fig(n, "A2", 17, "Figure 4.1 — How X_{ij} is computed: pair the cells below and diagonally (sl. 17)", clip=K, width_cm=10)
n.h2("Worked Example: baaba (sl. 11–18)")
n.code(["S → AB | BC    A → BA | a    B → CC | b    C → AB | a"])
cyk(G_SLIDE, "baaba")
n.h2("Exam Approach")
n.numbered(["Bottom row: for each symbol the variables with A → symbol.",
            "Row of length L: for each cell try every split k; for each pair (B in left cell, C in right cell) collect "
            "the heads A → BC. Write the pairs you tried in rough work.",
            "Top cell: answer 'w ∈ L(G)' iff S is in it.",
            "If asked to describe L(G), read the CNF rules backwards into a familiar grammar."])
n.callout("trap", "X_{ij} uses ALL splits k = i … j−1, not only the middle one. A missing variable in a low row propagates "
          "upward — double-check the bottom two rows.")
n.practice("Lesson 4", "(a) Actual — 2023-24 Q6, 2019-20 Q7, Jan-2020 Q7. (b) Actual — 2022-23 Q7. (c) Actual — 2017-18 Q7(b). "
           "(d) Actual — 2007-08 Q13.",
           ["(a) G (CNF): S → BZ | CY | ZZ | YY, B → ZA, C → YA, A → ZA | YA | 0 | 1, Z → 0, Y → 1. Using CYK determine "
            "whether 0010 (2023-24), 01100 (2019-20), 10011 (Jan-2020) is in L(G). Describe L(G). (15)",
            "(b) G: S → AB | AY | YA | 1, A → ZA | YA | 0 | 1, B → YA, Z → 0, Y → 1. Is 0100 in L(G)? (15)",
            "(c) Using the CNF grammar of Lesson 3 (a), is 01101 in the language? (7)",
            "(d) CNF definition; CYK for abaab with S → AB | BC, A → BA | a, B → CC | b, C → AB | a. (10)"])
n.solution()
n.answer("(a)", "A ⇒∗ any non-empty binary string (A → ZA | YA | 0 | 1); B ⇒ 0A, C ⇒ 1A. So S → BZ = 0(0|1)⁺0, CY = "
         "1(0|1)⁺1, ZZ = 00, YY = 11: **L(G) = binary strings of length ≥ 2 whose first and last symbols are equal** "
         "(checked by program). Tables:")
cyk(G_SAME, "0010")
cyk(G_SAME, "01100")
cyk(G_SAME, "10011")
n.answer("(b)", "")
cyk(G_2223, "0100")
n.p("L(G): S → AY | YA | AB … gives non-empty strings containing a 1 in a suitable position; CYK only needs the table.")
n.answer("(c)", "CNF: S → VA | UA | AU | 1, V → AU, A → ZA | UA | 0 | 1, Z → 0, U → 1.")
cyk(CNF_1718, "01101")
n.answer("(d)", "CNF definition: Lesson 3.")
cyk(G_SLIDE, "abaab")

